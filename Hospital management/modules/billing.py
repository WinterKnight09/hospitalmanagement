
# HOSPITAL BILLING MODULE

import os
import shutil
from decimal import Decimal, InvalidOperation

from modules import session

from database.billingdatabase import (
    get_patient_for_billing,
    save_bill,
    get_bill_by_id
)


def clear_screen():
    os.system('cls' if os.name == 'nt' else 'clear')


def get_width():
    return max(shutil.get_terminal_size().columns, 85)


def line():
    print("=" * get_width())


def display_header(user):

    width = get_width()

    print("=" * width)
    print("HOSPITAL MANAGEMENT SYSTEM".center(width))
    print("HOSPITAL ADMINISTRATION PORTAL".center(width))
    print("=" * width)

    print(f"Welcome, {user['name']}!".rjust(width))
    print(f"Role: {user['role']}".rjust(width))

    print("\n" + "=" * width)
    print("HOSPITAL BILLING MODULE".center(width))
    print("=" * width)


def get_amount(label):

    while True:

        value = input(f"{label:<30}: Rs. ").strip()

        try:
            amount = Decimal(value)

            if not amount.is_finite() or amount < 0:
                print("Enter a valid non-negative amount.")
                continue

            return amount.quantize(Decimal("0.01"))

        except InvalidOperation:
            print("Please enter a valid numeric amount.")


def display_invoice(bill):

    clear_screen()

    width = get_width()

    print("=" * width)
    print("CITY HOSPITAL".center(width))
    print("PATIENT BILL / INVOICE".center(width))
    print("=" * width)

    print(f"\nInvoice Number : {bill['INVOICE_NUMBER']}")
    print(f"Bill ID        : {bill['BILL_ID']}")
    print(f"Bill Date      : {bill['BILL_DATE']}")

    print("\nPATIENT DETAILS")
    line()

    print(f"Patient ID     : {bill['PATIENT_ID']}")
    print(f"Patient Name   : {bill['PATIENT_NAME']}")
    print(f"Mobile Number  : {bill['MOBILE_NUMBER']}")

    print("\nBILL BREAKDOWN")
    line()

    print(f"{'Consultation Fee':<35} Rs. {bill['CONSULTATION_FEE']:.2f}")
    print(f"{'Medicine Charges':<35} Rs. {bill['MEDICINE_CHARGES']:.2f}")
    print(f"{'Test Charges':<35} Rs. {bill['TEST_CHARGES']:.2f}")

    line()

    print(f"{'TOTAL AMOUNT':<35} Rs. {bill['TOTAL_AMOUNT']:.2f}")

    print(f"\nPayment Status : {bill['PAYMENT_STATUS']}")
    print(f"Generated By   : {bill.get('GENERATED_BY') or 'Unknown'}")

    line()

    print("\nThank you for visiting our hospital!")

    line()


def billing_window():

    user = session.get_user()

    if user is None:
        print("No active user session!")
        input("\nPress Enter to continue...")
        return

    while True:

        clear_screen()
        display_header(user)

        print("\n1. Generate New Bill")
        print("0. Return to Main Menu")

        line()

        choice = input("\nEnter your choice: ").strip()

        if choice == "1":
            generate_bill(user)

        elif choice == "0":
            break

        else:
            print("\nInvalid choice!")
            input("\nPress Enter to continue...")


def generate_bill(user):

    clear_screen()

    display_header(user)

    print("\nPATIENT IDENTIFICATION")
    line()

    patient_id_input = input("\nEnter Patient ID: ").strip()

    if not patient_id_input.isdigit():
        print("\nPlease enter a valid numeric Patient ID.")
        input("\nPress Enter to continue...")
        return

    patient_id = int(patient_id_input)

    patient = get_patient_for_billing(patient_id)

    if patient is None:
        print("\nPatient not found, or database connection failed.")
        input("\nPress Enter to continue...")
        return

    print("\nPATIENT DETAILS")
    line()

    print(f"Patient ID     : {patient['PATIENT_ID']}")
    print(f"Patient Name   : {patient['PATIENT_NAME']}")
    print(f"Mobile Number  : {patient['MOBILE_NUMBER']}")
    print(f"Patient Type   : {patient['PATIENT_TYPE']}")

    print("\nENTER BILLING CHARGES")
    line()

    consultation = get_amount("Consultation Fees")
    medicine = get_amount("Medicine Charges")
    tests = get_amount("Test Charges")

    total = consultation + medicine + tests

    print("\nBILL SUMMARY")
    line()

    print(f"{'Consultation Fees':<30}: Rs. {consultation:.2f}")
    print(f"{'Medicine Charges':<30}: Rs. {medicine:.2f}")
    print(f"{'Test Charges':<30}: Rs. {tests:.2f}")

    line()

    print(f"{'TOTAL AMOUNT':<30}: Rs. {total:.2f}")

    line()

    confirm = input("\nGenerate and save this bill? (Y/N): ").strip().lower()

    if confirm != "y":
        print("\nBill generation cancelled.")
        input("\nPress Enter to continue...")
        return

    result = save_bill(
        patient_id,
        consultation,
        medicine,
        tests,
        user.get("user_id")
    )

    if result is None:
        print("\nUnable to save the bill.")
        input("\nPress Enter to continue...")
        return

    bill = get_bill_by_id(result["bill_id"])

    if bill is not None:
        display_invoice(bill)
    else:
        print("\nBill saved successfully!")
        print(f"Invoice Number: {result['invoice_number']}")
        print(f"Total Amount: Rs. {result['total']:.2f}")
        print("\nInvoice details could not be retrieved.")

    input("\nPress Enter to return to Billing Menu...")
